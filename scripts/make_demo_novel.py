CN = "零一二三四五六七八九"


def cn_num(n):
    if n <= 10:
        return "十" if n == 10 else CN[n]
    if n < 20:
        return "十" + CN[n % 10]
    tens, ones = divmod(n, 10)
    return CN[tens] + "十" + (CN[ones] if ones else "")


def main():
    random.seed(20261031)
    lines = ["雪夜行", "", "作者：示例", ""]

    for i in range(1, CHAPTERS + 1):
        lines.append(f"第{cn_num(i)}章 {TITLES[(i - 1) % len(TITLES)]}")
        lines.append("")
        for _ in range(random.randint(5, 9)):
            n = random.randint(2, 5)
            para = "".join(random.choice(SENTENCES) for _ in range(n))
            lines.append(para)
            lines.append("")

    text = "\n".join(lines)
    os.makedirs("samples", exist_ok=True)
    with open("samples/示例·雪夜行.txt", "wb") as f:
        f.write(text.encode("gb18030"))
    print(f"samples/示例·雪夜行.txt  {len(text)} 字 / {CHAPTERS} 章")


if __name__ == "__main__":
    main()
